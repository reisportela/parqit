uint32_t code_point(unsigned char b, LegacyEncoding enc) {
    if (b < 0x80) return b;
    switch (enc) {
    case LegacyEncoding::Windows1252: return kWindows1252High[b - 0x80];
    case LegacyEncoding::Latin1: return b;
    case LegacyEncoding::Latin9: return kLatin9High[b - 0x80];
    case LegacyEncoding::MacRoman: return kMacRomanHigh[b - 0x80];
    }
    return b;
}

void append_utf8(std::string *out, uint32_t cp) {
    if (cp < 0x80) {
        out->push_back(static_cast<char>(cp));
    } else if (cp < 0x800) {
        out->push_back(static_cast<char>(0xC0 | (cp >> 6)));
        out->push_back(static_cast<char>(0x80 | (cp & 0x3F)));
    } else {
        /* every table entry is in the BMP (< 0x10000) */
        out->push_back(static_cast<char>(0xE0 | (cp >> 12)));
        out->push_back(static_cast<char>(0x80 | ((cp >> 6) & 0x3F)));
        out->push_back(static_cast<char>(0x80 | (cp & 0x3F)));
    }
}

std::string lower_trim(const std::string &s) {
    size_t b = 0, e = s.size();
    while (b < e && std::isspace(static_cast<unsigned char>(s[b]))) b++;
    while (e > b && std::isspace(static_cast<unsigned char>(s[e - 1]))) e--;
    std::string out;
    out.reserve(e - b);
    for (size_t i = b; i < e; i++)
        out.push_back(static_cast<char>(std::tolower(static_cast<unsigned char>(s[i]))));
    return out;
}

