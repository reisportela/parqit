bool legacy_encoding_parse(const std::string &name, LegacyEncoding *out) {
    const std::string n = lower_trim(name);
    if (n.empty() || n == "windows-1252" || n == "windows1252" || n == "cp1252" ||
        n == "cp-1252") {
        *out = LegacyEncoding::Windows1252;
        return true;
    }
    if (n == "latin1" || n == "latin-1" || n == "iso-8859-1" || n == "iso8859-1" ||
        n == "iso88591") {
        *out = LegacyEncoding::Latin1;
        return true;
    }
    if (n == "latin9" || n == "latin-9" || n == "iso-8859-15" || n == "iso8859-15" ||
        n == "iso885915") {
        *out = LegacyEncoding::Latin9;
        return true;
    }
    if (n == "macroman" || n == "mac-roman" || n == "mac_roman" || n == "macintosh") {
        *out = LegacyEncoding::MacRoman;
        return true;
    }
    return false;
}

const char *legacy_encoding_name(LegacyEncoding enc) {
    switch (enc) {
    case LegacyEncoding::Windows1252: return "windows-1252";
    case LegacyEncoding::Latin1: return "latin1";
    case LegacyEncoding::Latin9: return "latin9";
    case LegacyEncoding::MacRoman: return "macroman";
    }
    return "windows-1252";
}

bool utf8_valid(const unsigned char *p, size_t n) {
    for (size_t i = 0; i < n;) {
        unsigned char c = p[i];
        if (c < 0x80) { i += 1; continue; }
        size_t extra;
        unsigned char low = 0x80, high = 0xBF;
        if (c >= 0xC2 && c <= 0xDF) { extra = 1; }
        else if (c == 0xE0) { extra = 2; low = 0xA0; }
        else if (c >= 0xE1 && c <= 0xEC) { extra = 2; }
        else if (c == 0xED) { extra = 2; high = 0x9F; }
        else if (c >= 0xEE && c <= 0xEF) { extra = 2; }
        else if (c == 0xF0) { extra = 3; low = 0x90; }
        else if (c >= 0xF1 && c <= 0xF3) { extra = 3; }
        else if (c == 0xF4) { extra = 3; high = 0x8F; }
        else return false; /* 0x80-0xC1, 0xF5-0xFF: not a valid lead byte */
        if (i + extra >= n) return false;
        if (p[i + 1] < low || p[i + 1] > high) return false;
        for (size_t kk = 2; kk <= extra; kk++)
            if (p[i + kk] < 0x80 || p[i + kk] > 0xBF) return false;
        i += extra + 1;
    }
    return true;
}

std::string legacy_to_utf8(const std::string &bytes, LegacyEncoding enc) {
    std::string out;
    out.reserve(bytes.size() + bytes.size() / 4);
    for (unsigned char b : bytes) append_utf8(&out, code_point(b, enc));
    return out;
}

bool utf8_or_transcode(std::string *s, LegacyEncoding enc) {
    if (utf8_valid(*s)) return false;
    *s = legacy_to_utf8(*s, enc);
    return true;
}

